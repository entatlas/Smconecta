export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [language, setLanguageState] = useState<Language>('pt-BR')
  const [mounted, setMounted] = useState(false)

  useEffect(() => {
    setMounted(true)
    const saved = localStorage.getItem('sm-lang') as Language
    if (saved && dictionaries[saved]) {
      setLanguageState(saved)
    }
  }, [])

  const setLanguage = (lang: Language) => {
    setLanguageState(lang)
    localStorage.setItem('sm-lang', lang)
  }

  const t = (key: string) => {
    const dict = dictionaries[language] || dictionaries['pt-BR']
    return (dict as any)[key] || key
  }

  // Prevents hydration mismatch on first render
  if (!mounted) {
    return (
      <I18nContext.Provider value={{ language: 'pt-BR', setLanguage, t: (key) => (dictionaries['pt-BR'] as any)[key] || key }}>
        {children}
      </I18nContext.Provider>
    )
  }

  return (
    <I18nContext.Provider value={{ language, setLanguage, t }}>
      {children}
    </I18nContext.Provider>
  )
}

export function useTranslation() {
  const context = useContext(I18nContext)
  if (!context) throw new Error('useTranslation must be used within I18nProvider')
  return context
}
